import { PrismaClient, UserRole, AuditAction } from "@prisma/client";
import * as bcrypt from "bcryptjs";
import * as crypto from "crypto";
import * as fs from "fs";
import * as path from "path";

// Attempt to load .env if process.env.DATABASE_URL is not set
function loadLocalEnv() {
  const candidates = [
    path.resolve(__dirname, "../.env"),
    path.resolve(__dirname, "../../.env"),
  ];
  for (const envPath of candidates) {
    if (fs.existsSync(envPath)) {
      const content = fs.readFileSync(envPath, "utf8");
      for (const line of content.split("\n")) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const idx = trimmed.indexOf("=");
        if (idx > 0) {
          const key = trimmed.slice(0, idx).trim();
          const val = trimmed.slice(idx + 1).trim().replace(/^["']|["']$/g, "");
          if (!process.env[key]) {
            process.env[key] = val;
          }
        }
      }
    }
  }
}

loadLocalEnv();

/**
 * MedCore HMS — Production SUPER_ADMIN Bootstrap Runner
 *
 * Ensures a secure, idempotent initialization of the initial platform administrator:
 * 1. Connects using the process environment DATABASE_URL.
 * 2. Checks if a SUPER_ADMIN already exists; aborts gracefully if one is present (no duplicates).
 * 3. Reads credentials from BOOTSTRAP_ADMIN_EMAIL and BOOTSTRAP_ADMIN_PASSWORD.
 * 4. If password is not provided in env, generates a cryptographically secure random password.
 * 5. Uses bcrypt with 12 salt rounds (matching auth service security standards).
 * 6. Records an immutable audit log of the bootstrap event.
 * 7. Never exposes password hashes or database credentials.
 */

function generateSecurePassword(): string {
  // Generate random base64 string and ensure all character classes for validation compliance
  const random = crypto.randomBytes(12).toString("base64").replace(/[+/=]/g, "x");
  return `MedCore#${random}9A!`;
}

export async function bootstrapSuperAdmin() {
  console.log("==========================================================================");
  console.log("🛡️  MedCore HMS — Platform Super Administrator Bootstrap");
  console.log("==========================================================================\n");

  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    console.error("❌ DATABASE_URL is not set in the environment.");
    process.exit(1);
  }

  // Display sanitized database destination
  try {
    const parsed = new URL(databaseUrl.trim());
    console.log("Database Destination (Sanitized):");
    console.log(`  • Host:     ${parsed.hostname}`);
    console.log(`  • Database: ${parsed.pathname.replace(/^\/+/, "") || "default"}\n`);
  } catch {
    console.log("  • Database target parsed.\n");
  }

  const prisma = new PrismaClient({
    datasources: { db: { url: databaseUrl.trim() } },
  });

  try {
    // 1. Check for existing SUPER_ADMIN account
    const existingAdmin = await prisma.user.findFirst({
      where: { role: UserRole.SUPER_ADMIN },
      select: { id: true, email: true, createdAt: true, isActive: true },
    });

    if (existingAdmin) {
      console.log("ℹ️  A SUPER_ADMIN account already exists in this database:");
      console.log(`   • ID:         ${existingAdmin.id}`);
      console.log(`   • Email:      ${existingAdmin.email}`);
      console.log(`   • Active:     ${existingAdmin.isActive}`);
      console.log(`   • Created At: ${existingAdmin.createdAt.toISOString()}`);
      console.log("\n✅ Bootstrap aborted safely: No duplicate administrators created.");
      console.log("==========================================================================");
      return { created: false, user: existingAdmin };
    }

    // 2. Determine credentials
    const email = (process.env.BOOTSTRAP_ADMIN_EMAIL || "superadmin@medcore.io").trim().toLowerCase();
    const isAutoGenerated = !process.env.BOOTSTRAP_ADMIN_PASSWORD;
    const rawPassword = process.env.BOOTSTRAP_ADMIN_PASSWORD || generateSecurePassword();

    // 3. Hash password with bcrypt (12 rounds)
    const passwordHash = bcrypt.hashSync(rawPassword, 12);

    // 4. Create initial SUPER_ADMIN in transaction with audit log
    const result = await prisma.$transaction(async (tx) => {
      const user = await tx.user.create({
        data: {
          email,
          passwordHash,
          firstName: "System",
          lastName: "SuperAdmin",
          role: UserRole.SUPER_ADMIN,
          hospitalId: null, // Global platform scope
          isActive: true,
        },
        select: {
          id: true,
          email: true,
          role: true,
          isActive: true,
          createdAt: true,
        },
      });

      await tx.auditLog.create({
        data: {
          action: AuditAction.CREATE,
          entityName: "User",
          entityId: user.id,
          details: {
            action: "BOOTSTRAP_SUPER_ADMIN",
            email: user.email,
            role: user.role,
            timestamp: new Date().toISOString(),
          },
        },
      });

      return user;
    });

    console.log("🎉 Initial Platform Super Administrator created successfully!");
    console.log(`  • User ID:  ${result.id}`);
    console.log(`  • Email:    ${result.email}`);
    console.log(`  • Role:     ${result.role}`);
    console.log(`  • Status:   ${result.isActive ? "ACTIVE" : "INACTIVE"}`);

    if (isAutoGenerated) {
      console.log("\n⚠️  IMPORTANT: An auto-generated temporary password was assigned:");
      console.log(`    Temporary Password: ${rawPassword}`);
      console.log("    Please record this password securely now. You can change it after login.");
    } else {
      console.log("\n✅ Configured using BOOTSTRAP_ADMIN_PASSWORD from the environment.");
    }

    console.log("\n==========================================================================");
    return { created: true, user: result, temporaryPassword: isAutoGenerated ? rawPassword : undefined };
  } catch (error: any) {
    console.error("❌ Bootstrap failed with error:", error.message || error);
    process.exit(1);
  } finally {
    await prisma.$disconnect();
  }
}

if (require.main === module) {
  bootstrapSuperAdmin().catch((e) => {
    console.error("Fatal bootstrap error:", e);
    process.exit(1);
  });
}
